  varimp_rows$brt <- data.frame(
    variable  = brt_imp$var,
    algorithm = "BRT",
    importance = brt_imp$rel.inf
  )
}

if (length(varimp_rows) > 0) {
  varimp_df   <- do.call(rbind, varimp_rows)
  varimp_path <- file.path(output_dir, "variable_importance.csv")
  write.csv(varimp_df, varimp_path, row.names = FALSE)
  log_info("Written: %s", varimp_path)

  rf_top <- varimp_df[varimp_df$algorithm == "RandomForest", ]
  rf_top <- rf_top[order(rf_top$importance, decreasing = TRUE), ][seq_len(min(5, nrow(rf_top))), ]
  log_info("Top predictors (RF): %s", paste(rf_top$variable, collapse = ", "))
} else {
  log_warn("Variable importance not computed (RF not fitted).")
}

# ── 13. Response curves (partial dependence) ───────────────────────────────────
log_step(13, "Generate response curves (partial dependence)")

ref_model <- final_models$maxent %||% final_models$rf

if (!is.null(ref_model)) {
  log_info("Generating partial dependence curves for %d predictors...", length(selected_preds))
  ref_row <- as.data.frame(lapply(train_df[, -1, drop = FALSE], median, na.rm = TRUE))
  n_seq   <- 100

  plot_df <- do.call(rbind, lapply(selected_preds, function(pred_nm) {
    x_range <- range(train_df[[pred_nm]], na.rm = TRUE)
    x_seq   <- seq(x_range[1], x_range[2], length.out = n_seq)
    tmp     <- ref_row[rep(1L, n_seq), , drop = FALSE]
    tmp[[pred_nm]] <- x_seq
    suit <- tryCatch({
      if (!is.null(final_models$maxent))
        as.numeric(predict(final_models$maxent, tmp, type = "cloglog"))
      else
        as.numeric(predict(final_models$rf, tmp, type = "prob")[, "1"])
    }, error = function(e) rep(NA_real_, n_seq))
    data.frame(predictor = pred_nm, x = x_seq, suitability = suit)
  }))

  n_cols  <- min(3L, length(selected_preds))
  rc_plot <- ggplot(plot_df, aes(x = x, y = suitability)) +
    geom_line(colour = "#2166AC", linewidth = 0.8) +
    geom_hline(yintercept = p10_threshold, linetype = "dashed",
               colour = "firebrick", linewidth = 0.4) +
    facet_wrap(~predictor, scales = "free_x", ncol = n_cols) +
    labs(
      title    = "Response Curves — Ensemble SDM (partial dependence)",
      subtitle = sprintf("Red dashed line = P10 threshold (%.3f) | Other predictors at median",
                         p10_threshold),
      x = "Predictor value",
      y = "Ensemble suitability (0-1)"
    ) +
    scale_y_continuous(limits = c(0, 1)) +
    theme_bw(base_size = 10) +
    theme(strip.text = element_text(size = 8, face = "bold"))

  rc_path <- file.path(output_dir, "response_curves.png")
  ggplot2::ggsave(rc_path, rc_plot,
                  width  = 4 * n_cols,
                  height = 4 * ceiling(length(selected_preds) / n_cols),
                  dpi = 150, limitsize = FALSE)
  log_info("Written: %s", rc_path)
} else {
  log_warn("Response curves skipped: no MaxEnt or RF model available.")
}

