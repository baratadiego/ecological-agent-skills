# ── 12. Variable importance ────────────────────────────────────────────────────
log_step(12, "Compute and save variable importance")

varimp_rows <- list()

if (!is.null(final_models$rf)) {
  rf_imp <- as.data.frame(randomForest::importance(final_models$rf, type = 1))
  varimp_rows$rf <- data.frame(
    variable  = rownames(rf_imp),
    algorithm = "RandomForest",
    importance = rf_imp[, 1]
  )
}

if (!is.null(final_models$brt)) {
