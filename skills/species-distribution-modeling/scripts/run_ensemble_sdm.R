p10_threshold <- if (length(occ_suit) >= 5) {
  quantile(occ_suit, 0.10, na.rm = TRUE)
} else {
  log_warn("Too few valid suitability values at occurrence locations (%d). Using 0.5 as fallback.", length(occ_suit))
  0.5
}

log_info("P10 threshold: %.4f", p10_threshold)

binary_map <- terra::ifel(ens_mean >= p10_threshold, 1L, 0L)
terra::writeRaster(binary_map, file.path(output_dir, "suitability_binary.tif"),
                   overwrite = TRUE, datatype = "INT1U")
log_info("Written: suitability_binary.tif")

# Suitable area
cell_res_deg  <- mean(terra::res(ens_mean))
cell_area_km2 <- (cell_res_deg * 111.32)^2
suit_cells    <- sum(terra::values(binary_map) == 1L, na.rm = TRUE)
total_cells   <- sum(!is.na(terra::values(binary_map)))
suitable_km2  <- suit_cells   * cell_area_km2
total_km2     <- total_cells  * cell_area_km2
pct_suitable  <- 100 * suit_cells / total_cells
mean_suit     <- mean(terra::values(ens_mean), na.rm = TRUE)

summary_df <- data.frame(
  scenario          = "current",
  threshold_method  = "P10",
  threshold_value   = round(p10_threshold, 4),
  total_area_km2    = round(total_km2,    1),
  suitable_area_km2 = round(suitable_km2, 1),
  pct_suitable      = round(pct_suitable, 2),
  mean_suitability  = round(mean_suit,    4)
