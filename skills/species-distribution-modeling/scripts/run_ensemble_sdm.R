log_info("Final models fitted: %s", paste(active_algos, collapse = ", "))

saveRDS(list(models = final_models, auc_weights = auc_weights),
        file.path(output_dir, "ensemble_models.rds"))
log_info("Written: ensemble_models.rds (with AUC weights)")

# ── 10. Predict over study area ───────────────────────────────────────────────
log_step(10, "Predict ensemble suitability over study area raster")

predict_raster <- function(model, stk, algo) {
  tryCatch({
    switch(algo,
      maxent = terra::predict(stk, model, type = "cloglog", na.rm = TRUE),
      brt    = terra::predict(stk, model, n.trees = brt_trees, type = "response", na.rm = TRUE),
      rf     = terra::predict(stk, model, type = "prob", index = 2L, na.rm = TRUE)
    )
  }, error = function(e) {
    log_warn("Raster prediction failed for %s: %s", algo, conditionMessage(e)); NULL
  })
}

pred_rasters <- Filter(Negate(is.null),
  setNames(lapply(active_algos, function(a) predict_raster(final_models[[a]], stack_sel, a)),
           active_algos))

if (length(pred_rasters) == 0) {
  log_error("All raster predictions failed.\nProbable cause: terra::predict incompatibility with model object type.\nPrevious skill: species-distribution-modeling")
  stop("No valid raster predictions produced.")
}

pred_stack <- terra::rast(pred_rasters)
w_raster   <- auc_weights[names(pred_rasters)]
w_raster   <- w_raster / sum(w_raster)  # re-normalise in case an algo failed
ens_mean   <- terra::app(pred_stack, fun = function(x) weighted.mean(x, w_raster, na.rm = TRUE))
ens_sd     <- if (terra::nlyr(pred_stack) > 1)
                terra::app(pred_stack, sd, na.rm = TRUE) else
                ens_mean * 0

terra::writeRaster(ens_mean, file.path(output_dir, "suitability_current.tif"), overwrite = TRUE)
terra::writeRaster(ens_sd,   file.path(output_dir, "ensemble_sd.tif"),         overwrite = TRUE)
log_info("Written: suitability_current.tif")
log_info("Written: ensemble_sd.tif")

