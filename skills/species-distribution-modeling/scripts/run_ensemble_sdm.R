# ── 5. Spatial block cross-validation ─────────────────────────────────────────
log_step(5, "Spatial block cross-validation setup")
cv_k <- p$modeling$cv_folds %||% 5

log_decision("cv_method", "spatial_block",
             "blockCV::cv_spatial avoids AUC inflation from spatial autocorrelation (Valavi et al. 2019)")
log_decision("cv_folds", cv_k, "k folds from params.yaml")

all_pts <- rbind(
  data.frame(occ_pts_df, pa = 1L),
  data.frame(bg_pts_df,  pa = 0L)
)
all_sf <- sf::st_as_sf(all_pts, coords = c("x", "y"), crs = 4326)

cv_folds <- tryCatch({
  blockCV::cv_spatial(
    x        = all_sf,
    column   = "pa",
    r        = stack_sel[[1]],
    k        = cv_k,
    hexagon  = FALSE,
    progress = FALSE
  )
}, error = function(e) {
  log_warn(
    "blockCV::cv_spatial failed: %s\nFalling back to random %d-fold CV.\nTo use spatial CV: install.packages('blockCV')",
    conditionMessage(e), cv_k
  )
  log_decision("cv_fallback", "random_kfold",
               "blockCV unavailable or insufficient spatial extent; using random k-fold")
  n <- nrow(all_pts)
  fold_ids <- sample(rep(seq_len(cv_k), length.out = n))
  list(
    folds_list = lapply(seq_len(cv_k), function(i) list(
      train = which(fold_ids != i),
      test  = which(fold_ids == i)
    ))
  )
})

log_info("Cross-validation folds ready: %d folds", cv_k)

# ── 6. Hyperparameters ────────────────────────────────────────────────────────
log_step(6, "Resolve model hyperparameters")

maxnet_rm <- p$hyperparameters$maxnet$regularization_multiplier %||% 1.0
if (length(maxnet_rm) > 1) maxnet_rm <- maxnet_rm[ceiling(length(maxnet_rm) / 2)]
maxnet_fc <- p$hyperparameters$maxnet$feature_classes %||% "LQH"

brt_lr    <- p$hyperparameters$brt$learning_rate    %||% 0.01
brt_trees <- p$hyperparameters$brt$n_trees          %||% 500
brt_depth <- p$hyperparameters$brt$tree_complexity  %||% 3
rf_ntree  <- p$hyperparameters$rf$n_trees           %||% 500

log_decision("maxnet_rm",  maxnet_rm,  "regularization multiplier; use tuned value from tune_maxnet.R when available")
log_decision("maxnet_fc",  maxnet_fc,  "feature class combination for MaxEnt")
log_decision("brt_lr",     brt_lr,     "BRT learning rate from params.yaml or default 0.01")
log_decision("brt_trees",  brt_trees,  "BRT number of trees from params.yaml or default 500")
log_decision("brt_depth",  brt_depth,  "BRT tree complexity from params.yaml or default 3")
log_decision("rf_ntree",   rf_ntree,   "RF number of trees from params.yaml or default 500")

algorithms <- tolower(p$modeling$algorithms %||% c("maxent", "brt", "rf"))
log_info("Algorithms: %s", paste(algorithms, collapse = ", "))

# ── 7. Performance helpers ─────────────────────────────────────────────────────
compute_auc <- function(pred_1, pred_0) {
  n1 <- length(pred_1); n0 <- length(pred_0)
  if (n1 == 0 || n0 == 0) return(NA_real_)
  (sum(outer(pred_1, pred_0, ">")) + 0.5 * sum(outer(pred_1, pred_0, "=="))) / (n1 * n0)
}

compute_tss <- function(pred_1, pred_0) {
  thresholds <- sort(unique(c(pred_1, pred_0)))
  if (length(thresholds) == 0) return(NA_real_)
  tss_vals <- vapply(thresholds, function(th) {
    mean(pred_1 >= th) + mean(pred_0 < th) - 1
  }, numeric(1))
  max(tss_vals, na.rm = TRUE)
}

# ── 8. Cross-validation loop ──────────────────────────────────────────────────
log_step(8, "Fit models with cross-validation (MaxEnt, BRT, RF)")

folds_list <- cv_folds$folds_list
cv_results <- vector("list", cv_k)

for (fold_i in seq_len(cv_k)) {
  log_info("Fold %d/%d ...", fold_i, cv_k)

  tr_idx <- folds_list[[fold_i]]$train
  te_idx <- folds_list[[fold_i]]$test

  tr <- train_df[tr_idx, , drop = FALSE]
  te <- train_df[te_idx, , drop = FALSE]
  te_pa  <- te$pa
  tr_env <- tr[, -1, drop = FALSE]
  te_env <- te[, -1, drop = FALSE]

  preds_fold <- list()

  # MaxEnt
  if (any(c("maxent", "maxnet") %in% algorithms)) {
    mx <- tryCatch(
      maxnet::maxnet(p = tr$pa, data = tr_env, regmult = maxnet_rm,
                     f = maxnet::maxnet.formula(tr$pa, tr_env,
                                                classes = tolower(maxnet_fc))),
      error = function(e) {
        log_warn("MaxEnt fold %d failed: %s", fold_i, conditionMessage(e)); NULL
      }
    )
    if (!is.null(mx))
      preds_fold$maxent <- as.numeric(predict(mx, te_env, type = "cloglog"))
  }

  # BRT
  if (any(c("brt", "gbm") %in% algorithms)) {
    brt <- tryCatch(
      gbm::gbm(pa ~ ., data = tr, distribution = "bernoulli",
                n.trees = brt_trees, interaction.depth = brt_depth,
                shrinkage = brt_lr, bag.fraction = 0.75, verbose = FALSE),
      error = function(e) {
        log_warn("BRT fold %d failed: %s", fold_i, conditionMessage(e)); NULL
      }
    )
    if (!is.null(brt))
      preds_fold$brt <- as.numeric(predict(brt, te, n.trees = brt_trees, type = "response"))
  }

  # Random Forest
  if (any(c("rf", "randomforest") %in% algorithms)) {
    rf_tr <- tr; rf_tr$pa <- as.factor(rf_tr$pa)
    rf <- tryCatch(
      randomForest::randomForest(pa ~ ., data = rf_tr, ntree = rf_ntree),
      error = function(e) {
        log_warn("RF fold %d failed: %s", fold_i, conditionMessage(e)); NULL
      }
    )
    if (!is.null(rf))
      preds_fold$rf <- as.numeric(predict(rf, te, type = "prob")[, "1"])
  }

  if (length(preds_fold) > 0) {
    pred_mat <- do.call(cbind, preds_fold)

    # Compute per-algorithm AUC for this fold
    fold_aucs <- vapply(names(preds_fold), function(a) {
      compute_auc(preds_fold[[a]][te_pa == 1], preds_fold[[a]][te_pa == 0])
    }, numeric(1))
    fold_aucs[is.na(fold_aucs)] <- 0

    # AUC-weighted ensemble (fall back to equal weights if all AUCs are zero)
    if (sum(fold_aucs) > 0) {
      w <- fold_aucs / sum(fold_aucs)
      ens_pred <- as.numeric(pred_mat %*% w)
    } else {
      ens_pred <- rowMeans(pred_mat, na.rm = TRUE)
    }

    p1 <- ens_pred[te_pa == 1]
    p0 <- ens_pred[te_pa == 0]

    cv_results[[fold_i]] <- data.frame(
      fold    = fold_i,
      n_train = nrow(tr),
      n_test  = nrow(te),
      auc_maxent = if (!is.null(preds_fold$maxent))
        compute_auc(preds_fold$maxent[te_pa==1], preds_fold$maxent[te_pa==0]) else NA_real_,
      auc_brt    = if (!is.null(preds_fold$brt))
        compute_auc(preds_fold$brt[te_pa==1],    preds_fold$brt[te_pa==0])    else NA_real_,
      auc_rf     = if (!is.null(preds_fold$rf))
        compute_auc(preds_fold$rf[te_pa==1],     preds_fold$rf[te_pa==0])     else NA_real_,
      auc_ensemble = compute_auc(p1, p0),
      tss_ensemble = compute_tss(p1, p0)
    )
  } else {
    log_warn("No models succeeded in fold %d.", fold_i)
    cv_results[[fold_i]] <- data.frame(fold = fold_i, n_train = nrow(tr), n_test = nrow(te),
      auc_maxent = NA, auc_brt = NA, auc_rf = NA, auc_ensemble = NA, tss_ensemble = NA)
  }
}

cv_df <- do.call(rbind, cv_results)
write.csv(cv_df, file.path(output_dir, "cv_performance.csv"), row.names = FALSE)
log_info("Written: cv_performance.csv")
log_info("CV AUC mean: %.3f (SD: %.3f) | TSS mean: %.3f (SD: %.3f)",
         mean(cv_df$auc_ensemble, na.rm = TRUE), sd(cv_df$auc_ensemble, na.rm = TRUE),
         mean(cv_df$tss_ensemble, na.rm = TRUE), sd(cv_df$tss_ensemble, na.rm = TRUE))

# ── Compute AUC-based ensemble weights from CV results ────────────────────────
algo_aucs <- c(
  maxent = mean(cv_df$auc_maxent, na.rm = TRUE),
  brt    = mean(cv_df$auc_brt,    na.rm = TRUE),
  rf     = mean(cv_df$auc_rf,     na.rm = TRUE)
)
algo_aucs <- algo_aucs[!is.na(algo_aucs)]
if (length(algo_aucs) > 0 && sum(algo_aucs) > 0) {
  auc_weights <- algo_aucs / sum(algo_aucs)
} else {
  auc_weights <- setNames(rep(1 / length(active_algos), length(active_algos)), active_algos)
}
log_decision("ensemble_weighting", "AUC-weighted",
             "Weights proportional to mean CV AUC per algorithm — avoids mixing incompatible output scales equally")
log_info("Ensemble weights: %s",
         paste(sprintf("%s=%.3f", names(auc_weights), auc_weights), collapse = ", "))

auc_mean <- mean(cv_df$auc_ensemble, na.rm = TRUE)
auc_min  <- p$decision_points$auc_min_acceptable %||% 0.7
if (!is.na(auc_mean) && auc_mean < auc_min) {
  log_warn(
    "Ensemble AUC (%.3f) is below the minimum acceptable threshold (%.2f).\nConsider: revising predictors, expanding calibration area, or reviewing occurrence data quality.",
    auc_mean, auc_min
  )
}

